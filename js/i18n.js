export const LANGS = ["en", "zh"];
const KEY = "solbysol.lang";

function initialLang() {
  const fromUrl = new URLSearchParams(location.search).get("lang");
  if (LANGS.includes(fromUrl)) return fromUrl;
  try {
    const saved = localStorage.getItem(KEY);
    if (LANGS.includes(saved)) return saved;
  } catch { /* storage blocked */ }
  return "en";
}

let lang = typeof location === "undefined" ? "en" : initialLang();

export const getLang = () => lang;

export function setLang(next) {
  if (!LANGS.includes(next)) return;
  lang = next;
  try { localStorage.setItem(KEY, next); } catch { /* storage blocked */ }
}

// t("game.sol", { n: 3 }) → "Sol 3"
export function t(key, params = {}) {
  const s = DICT[lang][key] ?? DICT.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? ""));
}

// [5,6,7,9] → "5–7, 9"
function ranges(nums) {
  const out = [];
  for (let i = 0; i < nums.length; i++) {
    let j = i;
    while (nums[j + 1] === nums[j] + 1) j++;
    out.push(j > i ? `${nums[i]}–${nums[j]}` : `${nums[i]}`);
    i = j;
  }
  return out.join(t("fmt.sep"));
}

// Like t(), but expands game-logic params into the current language:
// sols (array of sol numbers), site / sites (ids), weather (key), sstrength (storm strength).
export function tr(key, params = {}) {
  const q = { ...params };
  if (Array.isArray(q.sols)) q.sols = t(q.sols.length > 1 ? "fmt.sols" : "fmt.sol", { list: ranges(q.sols) });
  if (typeof q.site === "string") q.site = t(`site.${q.site}.name`);
  if (Array.isArray(q.sites)) q.sites = q.sites.map((id) => t(`site.${id}.name`)).join(t("fmt.sep"));
  if (typeof q.weather === "string") q.weather = t(`weather.${q.weather}`);
  if (typeof q.sstrength === "string") q.sstrength = t(`sstrength.${q.sstrength}`);
  if (typeof q.part === "string" && DICT.en[`part.${q.part}`]) q.part = t(`part.${q.part}`);
  if (typeof q.tech === "string" && DICT.en[`techname.${q.tech}`]) q.tech = t(`techname.${q.tech}`);
  return t(key, q);
}

// Pick the current language from a { en, zh } object (used by facts).
export const pick = (obj) => (typeof obj === "string" ? obj : obj[lang] ?? obj.en);

// Fill static HTML: data-i18n (text), data-i18n-html (markup), data-i18n-aria (aria-label).
export function applyStatic(root = document) {
  document.documentElement.lang = lang === "zh" ? "zh-CN" : "en";
  document.title = t("meta.title");
  root.querySelectorAll("[data-i18n]").forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll("[data-i18n-html]").forEach((el) => { el.innerHTML = t(el.dataset.i18nHtml); });
  root.querySelectorAll("[data-i18n-aria]").forEach((el) => { el.setAttribute("aria-label", t(el.dataset.i18nAria)); });
}
